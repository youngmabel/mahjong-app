/**
 * Import a tile set's flat faces (assets/tiles/<style>/faces-svg, listed in tiles.json) into the code as
 * src/ui/tiles/<style>-faces.ts, which the screen packs into one hidden SVG sprite.
 *
 * The Clean faces come from the 3D tile project (October 28, 2026): the same drawings are the face
 * textures of the 3D tiles, so the 2D and 3D tiles match. Their lettering is already converted to
 * outlines (Inter and Noto Sans CJK, both under the SIL Open Font License), so tiles look the same on
 * every device. Long decimals are rounded to 2 places to keep the page small.
 *
 *   npm run import-tiles            (Clean, the only set so far)
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

interface Entry {
  svg: string;
  code: string | null;
  tile_ids?: number[];
  variant?: number;
}

const style = process.argv[2] ?? 'clean';
const dir = join('assets', 'tiles', style);
const list = JSON.parse(readFileSync(join(dir, 'tiles.json'), 'utf8')) as { tiles: Entry[] };

function symbolIdFor(e: Entry): string {
  if (e.code === null) return 't-back';
  if (e.code === 'F') {
    const id = (e.tile_ids ?? [])[0];
    if (id === undefined || id < 136 || id > 143) throw new Error(`flower ${e.svg} has no physical tile id 136-143`);
    return `t-F${id - 136}`;
  }
  return `t-${e.code}`;
}

function inner(svg: string, file: string): string {
  const m = /^\s*<svg\b[^>]*viewBox="0 0 64 88"[^>]*>([\s\S]*)<\/svg>\s*$/.exec(svg);
  if (!m) throw new Error(`${file} is not a 64 x 88 face`);
  const body = (m[1] as string).replace(/-?\d+\.\d{3,}/g, (x) => String(Number(Number(x).toFixed(2))));
  if (/<(metadata|title|desc|script)\b|<!--/.test(body)) throw new Error(`${file} carries metadata or script`);
  return body;
}

const faces: Record<string, string> = {};
for (const e of list.tiles) {
  const id = symbolIdFor(e);
  if (faces[id]) throw new Error(`two faces for ${id}`);
  faces[id] = inner(readFileSync(join(dir, e.svg), 'utf8'), e.svg);
}
const out = [
  `/* Generated by scripts/import-tiles.ts from assets/tiles/${style}/faces-svg. Do not edit by hand. */`,
  '',
  `export const ${style.toUpperCase()}_FACES: Record<string, string> = ${JSON.stringify(faces, null, 1)};`,
  '',
].join('\n');
writeFileSync(join('src', 'ui', 'tiles', `${style}-faces.ts`), out);
console.log(`${Object.keys(faces).length} faces, ${(out.length / 1024).toFixed(1)} KB`);
